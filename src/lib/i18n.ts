export function translate(locale: string, text: string): string {
  if (locale === "ar") return text;
  return translations[isLocale(locale) && locale !== "ar" ? locale : "en"][text] ?? text;
}

export function localizedValue<T>(translationsJson: string | null | undefined, locale: string, fallback: T): T {
  if (locale === "ar" || !translationsJson) return fallback;
  const localeMap = translations[isLocale(locale) && locale !== "ar" ? locale : "en"];
  try {
    const values: unknown = JSON.parse(translationsJson);
    if (typeof values === "object" && values !== null) {
      const value = (values as Record<string, unknown>)[locale];
      if (typeof value === "string" && value.trim()) return value as T;
    }
  } catch (error) {
    console.error("Invalid localized content JSON.", error);
  }
  return (localeMap[fallback as string] as T | undefined) ?? fallback;
}
